"""Génère results/eval_report.md (en anglais) à partir des derniers runs de results/.

    uv run python -m triage.eval.report
"""

import json
from pathlib import Path

from triage.eval.metrics import (accuracy, confusion, expected_calibration_error, none_precision_recall,
                                 percentile, routing_at)

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "results"
ADAPTERS = {"wazn": "Wazn-2B", "strands": "Strands Decider 2B", "rules": "Rules (baseline)"}
THRESHOLDS = [round(0.3 + 0.05 * i, 2) for i in range(14)]  # 0.30 à 0.95
LABELS = ["code_defect", "configuration", "capacity", "dependency", "security_certificate", "data_quality", "NONE"]
SHORT = {"code_defect": "code", "configuration": "config", "capacity": "capacity", "dependency": "downstream",
         "security_certificate": "security", "data_quality": "data", "NONE": "NONE"}


def latest_runs(prefix: str = "run") -> dict[str, dict]:
    runs = {}
    for adapter in ADAPTERS:
        files = sorted(RESULTS.glob(f"{prefix}_{adapter}_*.json"))
        if files:
            runs[adapter] = json.loads(files[-1].read_text(encoding="utf-8")) | {"file": files[-1].name}
    return runs


def latest_file(prefix: str) -> dict | None:
    files = sorted(RESULTS.glob(f"{prefix}_*.json"))
    return json.loads(files[-1].read_text(encoding="utf-8")) if files else None


def pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.0%}"


def summary(run: dict) -> dict:
    rows = run["incidents"]
    at = routing_at(rows, run["threshold"])
    none_p, none_r = none_precision_recall(rows)
    latencies = [r["latency_ms"] for r in rows]
    tokens = [r["input_tokens"] for r in rows if r.get("input_tokens")]
    by_source = {s: [r for r in rows if r["source"] == s] for s in ("victim-app", "handwritten")}
    out = {"Accuracy (all incidents)": pct(accuracy(rows))}
    if any(r["ambiguous"] for r in rows):
        out["Accuracy without ambiguous cases"] = pct(accuracy(rows, include_ambiguous=False))
    if all(by_source.values()):
        out["Accuracy on victim-app incidents"] = pct(accuracy(by_source["victim-app"]))
        out["Accuracy on hand-written incidents (other apps)"] = pct(accuracy(by_source["handwritten"]))
    return out | {
        "NONE: precision / recall": f"{pct(none_p)} / {pct(none_r)}",
        f"Handled without escalation (threshold {run['threshold']})": f"{pct(at['coverage'])} ({at['automatic']}/{len(rows)})",
        "Precision of automatic actions": pct(at["automatic_precision"]),
        "Wrong automatic actions": str(at["automatic_wrong"]),
        "ECE (calibration, 0 is perfect)": f"{expected_calibration_error(rows):.3f}",
        "Latency p50 / p95": f"{percentile(latencies, 50) / 1000:.1f} s / {percentile(latencies, 95) / 1000:.1f} s"
        if max(latencies) >= 100 else f"{percentile(latencies, 50):.2f} ms / {percentile(latencies, 95):.2f} ms",
        "Tokens read per incident (mean)": f"{sum(tokens) / len(tokens):.0f}" if tokens else "n/a",
    }


def table(header: list[str], lines: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(line) + " |" for line in lines]
    return "\n".join(out)


def confusion_table(rows: list[dict]) -> str:
    matrix = confusion(rows)
    lines = [[f"**{SHORT[e]}**"] + [str(matrix[e][p]) if matrix[e][p] else "." for p in LABELS] for e in LABELS]
    return table(["expected (row) / predicted (column)"] + [SHORT[p] for p in LABELS], lines)


def results_section(runs: dict[str, dict]) -> list[str]:
    summaries = {a: summary(r) for a, r in runs.items()}
    metrics = list(next(iter(summaries.values())))
    return [table(["Metric"] + [ADAPTERS[a] for a in runs], [[m] + [summaries[a][m] for a in runs] for m in metrics])]


def errors_section(runs: dict[str, dict], title: str) -> list[str]:
    out = []
    for adapter, run in runs.items():
        errors = [r for r in run["incidents"] if r["predicted"] != r["expected"]]
        out += [f"### Errors, {ADAPTERS[adapter]}{title} ({len(errors)})", ""]
        if errors:
            out.append(table(["id", "scenario", "expected", "predicted (confidence)", "ambiguous", "escalated"],
                             [[r["id"], r["scenario"], r["expected"], f"{r['predicted']} ({r['confidence']:.2f})",
                               "yes" if r["ambiguous"] else "", "yes" if r["escalated"] else "**no**"]
                              for r in errors]))
        out.append("")
    return out


def build(runs: dict[str, dict], robust: dict[str, dict]) -> str:
    first = next(iter(runs.values()))
    rows = first["incidents"]
    sources = {s: sum(r["source"] == s for r in rows) for s in ("victim-app", "handwritten")}
    out = [
        "# Argos Triage Gate: evaluation report",
        "",
        "_Generated by `uv run python -m triage.eval.report` from the model outputs in `results/`._",
        "",
        f"- **Evaluation set**: {len(rows)} incidents ({sources['victim-app']} from victim-app, "
        f"{sources['handwritten']} hand-written for other apps), including "
        f"{sum(r['expected'] == 'NONE' for r in rows)} out of scope (NONE expected) and "
        f"{sum(r['ambiguous'] for r in rows)} ambiguous.",
        f"- **Confidence threshold**: {first['threshold']}, fixed before the evaluation. The threshold tables below "
        "describe the trade-off; they were not used to pick the threshold.",
    ]
    for adapter, run in runs.items():
        out.append(f"- **{ADAPTERS[adapter]}**: `{run['file']}`, {run['hardware']}")

    out += ["", "## Results, main set", ""]
    out += results_section(runs)

    out += ["", "## Trade-off by threshold", "",
            "Automatic action when the NONE gate is closed and confidence is at or above the threshold; "
            "escalation otherwise.", ""]
    for adapter, run in runs.items():
        out += [f"**{ADAPTERS[adapter]}**", ""]
        lines = []
        for t in THRESHOLDS:
            r = routing_at(run["incidents"], t)
            lines.append([f"{t:.2f}", pct(r["coverage"]), pct(r["automatic_precision"]), str(r["automatic_wrong"])])
        out += [table(["threshold", "without escalation", "automatic precision", "wrong actions"], lines), ""]

    out += ["## Confusion matrices, main set", ""]
    for adapter, run in runs.items():
        out += [f"**{ADAPTERS[adapter]}**", "", confusion_table(run["incidents"]), ""]

    out += ["## Errors, main set", ""] + errors_section(runs, "")

    if robust:
        rows_r = next(iter(robust.values()))["incidents"]
        out += ["## Robustness set", "",
                f"{len(rows_r)} incidents written before the model runs, with the rules left untouched afterwards: "
                "other languages (Python, Node.js, Go, Nginx), custom exceptions, French messages. They sit outside "
                "known Java signatures on purpose, to measure generalisation rather than the usual case.",
                ""]
        for adapter, run in robust.items():
            out.append(f"- **{ADAPTERS[adapter]}**: `{run['file']}`")
        out += [""] + results_section(robust) + ["", "**Confusion matrices**", ""]
        for adapter, run in robust.items():
            out += [f"_{ADAPTERS[adapter]}_", "", confusion_table(run["incidents"]), ""]
        out += errors_section(robust, " (robustness)")

    largek = latest_file("largek_wazn")
    if largek:
        out += ["## Large-K (Wazn)", "",
                f"Which team, out of {largek['k']}, must act? Teams and expected answers are in `data/services.yaml`. "
                "Strands is not included: it accepts at most 24 options. The first case of a run without warm-up "
                "includes initialisation, hence a higher latency.", ""]
        out.append(table(["scenario", "expected", "predicted (confidence)", "correct", "latency"],
                         [[r["scenario"], r["expected"], f"{r['predicted']} ({r['confidence']:.2f})",
                           "yes" if r["predicted"] == r["expected"] else "**no**", f"{r['latency_ms']:.0f} ms"]
                          for r in largek["incidents"]]))
        out.append("")

    ablation = latest_file("ablation_wazn")
    if ablation:
        out += ["## Effect of preprocessing (Wazn)", "",
                "The same incident sent raw, then extracted by `triage/preprocessing`.", ""]
        variants = {"brut": "raw", "extrait": "extracted"}
        out.append(table(["scenario", "input", "tokens read", "latency", "predicted (confidence)", "expected"],
                         [[r["scenario"], variants.get(r["variant"], r["variant"]), str(r["input_tokens"]),
                           f"{r['latency_ms']:.0f} ms", f"{r['predicted']} ({r['confidence']:.2f})", r["expected"]]
                          for r in ablation["rows"]]))
        out.append("")

    out += [
        "## What these numbers say, and what they don't",
        "",
        f"- **Small sample**: {len(rows)} incidents. One error more or less moves accuracy by about "
        f"{1 / len(rows):.0%}, so gaps of a few points are not significant.",
        "- **Favoured baseline**: the rules were written by someone who knows the victim-app scenarios. The "
        "robustness set is a better measure of generalisation.",
        "- **Human labels**: every label is justified in `data/incidents.jsonl`. Ambiguous cases are those where the "
        "log alone does not reveal the real cause.",
        "- **Latency**: inference time measured by the model server on the hardware listed for each run. It excludes "
        "network and queueing.",
        "- **Calibration (ECE)**: with so few cases per confidence bin, it is an indication, not proof.",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    runs = latest_runs("run")
    if not runs:
        raise SystemExit("Aucun run dans results/ : lancer d'abord `python -m triage.eval.run`.")
    report = RESULTS / "eval_report.md"
    report.write_text(build(runs, latest_runs("robust")), encoding="utf-8")
    print(f"Rapport : {report}")


if __name__ == "__main__":
    main()
